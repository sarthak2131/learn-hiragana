// Dynamic Shuffling Generator to guarantee fresh randomized order on every session!
export function getDynamicShuffledWords(count: number = 10): VocabularyWord[] {
  const shuffled = [...VOCABULARY_WORDS];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled.slice(0, count);
}
